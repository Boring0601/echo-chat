function normalizeText(value) {
  return String(value ?? '')
    .toLowerCase()
    .replace(/[\s，。,.!！?？；;：:"'“”‘’（）()【】[\]…—-]+/g, '');
}

function formatNumber(value) {
  const n = Number(value);
  if (!Number.isFinite(n)) return '';
  if (Math.abs(n - Math.round(n)) < 1e-10) return String(Math.round(n));
  return String(Number(n.toFixed(4)));
}

function dateTimeAnswer(text, now = new Date()) {
  if (/(几点开会|开会几点|会议几点|会议时间|约的几点|定的是几点)/.test(text)) {
    return null;
  }
  const asksDate =
    /(几号|几日|日期|星期几|周几|今天.*(?:几号|几日|星期)|今年.*(?:哪年|几年)|今天是什么日子)/.test(
      text
    );
  const asksTime = /(几点|什么时间|现在时间|当前时间|现在的时间)/.test(text);
  if (!asksDate && !asksTime) return null;

  const year = now.getFullYear();
  const month = now.getMonth() + 1;
  const day = now.getDate();
  const weekday = ['星期日', '星期一', '星期二', '星期三', '星期四', '星期五', '星期六'][
    now.getDay()
  ];
  const hh = String(now.getHours()).padStart(2, '0');
  const mm = String(now.getMinutes()).padStart(2, '0');
  const dateText = `${year}年${month}月${day}日，${weekday}`;
  const timeText = `${hh}:${mm}`;
  if (asksDate && asksTime) {
    return {
      kind: 'date',
      category: '时间',
      answer: `今天是${dateText}，现在是${timeText}。`
    };
  }
  if (asksDate) {
    return {
      kind: 'date',
      category: '时间',
      answer: `今天是${dateText}。`
    };
  }
  return {
    kind: 'date',
    category: '时间',
    answer: `现在是${timeText}。`
  };
}

function weatherAnswer(text) {
  if (/为什么|原因|怎么形成|原理/.test(text)) return null;
  const isWeather =
    /(天气怎么样|天气如何|会下雨吗|下雨吗|下雨不|要带伞吗|今天.*(?:天气|气温|带伞|穿什么|冷不冷|热不热)|明天.*(?:天气|气温|带伞|穿什么)|现在.*(?:气温|下雨)|外面.*(?:天气|下雨)|(?:下雨|天气).{0,4}(?:怎么办|带伞|穿什么))/.test(
      text
    );
  if (!isWeather) return null;
  return {
    kind: 'weather',
    category: '天气',
    answer:
      '我这边没有实时天气数据，不能乱报。你可以看一眼天气 App；如果你告诉我城市和温度，我可以帮你判断穿什么、要不要带伞。'
  };
}

