function unitAnswer(text) {
  for (const rule of UNIT_RULES) {
    const match = text.match(rule.re);
    if (!match) continue;
    const value = Number(match[1]);
    const result = rule.fn(value);
    return {
      kind: 'unit',
      category: '换算',
      answer: `${formatNumber(value)} ${rule.from} = ${formatNumber(result)} ${rule.to}。`
    };
  }
  return null;
}

function evaluateExpression(expression) {
  const tokens = expression.match(/\d+(?:\.\d+)?|[()+\-*/]/g);
  if (!tokens || tokens.length === 0) return null;
  let index = 0;

  function parseFactor() {
    const token = tokens[index];
    if (token === '+') {
      index += 1;
      return parseFactor();
    }
    if (token === '-') {
      index += 1;
      return -parseFactor();
    }
    if (token === '(') {
      index += 1;
      const value = parseExpression();
      if (tokens[index] !== ')') return null;
      index += 1;
      return value;
    }
    if (token == null || !/^\d/.test(token)) return null;
    index += 1;
    return Number(token);
  }

  function parseTerm() {
    let value = parseFactor();
    if (value == null) return null;
    while (tokens[index] === '*' || tokens[index] === '/') {
      const operator = tokens[index];
      index += 1;
      const right = parseFactor();
      if (right == null) return null;
      if (operator === '/' && Math.abs(right) < 1e-12) return null;
      value = operator === '*' ? value * right : value / right;
    }
    return value;
  }

  function parseExpression() {
    let value = parseTerm();
    if (value == null) return null;
    while (tokens[index] === '+' || tokens[index] === '-') {
      const operator = tokens[index];
      index += 1;
      const right = parseTerm();
      if (right == null) return null;
      value = operator === '+' ? value + right : value - right;
    }
    return value;
  }

  const result = parseExpression();
  if (result == null || index !== tokens.length) return null;
  return result;
}

function mathAnswer(text, now = new Date()) {
  const percent = text.match(
    /(\d+(?:\.\d+)?)\s*%\s*(?:的|of)\s*(\d+(?:\.\d+)?)/i
  );
  if (percent) {
    const value = (Number(percent[1]) / 100) * Number(percent[2]);
    return {
      kind: 'math',
      category: '计算',
      answer: `${percent[1]}% 的 ${percent[2]} 是 ${formatNumber(value)}。`
    };
  }

  const square = text.match(/(\d+(?:\.\d+)?)\s*的平方根/);
  if (square) {
    const value = Number(square[1]);
    if (value < 0) return null;
    return {
      kind: 'math',
      category: '计算',
      answer: `${formatNumber(value)} 的平方根是 ${formatNumber(Math.sqrt(value))}。`
    };
  }

  const power = text.match(/(\d+(?:\.\d+)?)\s*的(平方|立方)/);
  if (power) {
    const value = Number(power[1]);
    const result = power[2] === '平方' ? value ** 2 : value ** 3;
    return {
      kind: 'math',
      category: '计算',
      answer: `${formatNumber(value)} 的${power[2]}是 ${formatNumber(result)}。`
    };
  }

  const candidates = text.match(/[0-9]+(?:\.[0-9]+)?(?:\s*[+\-*/×÷]\s*[0-9]+(?:\.[0-9]+)?)+/g);
  if (!candidates || candidates.length === 0) return null;
  const expression = candidates.sort((a, b) => b.length - a.length)[0].replace(/×/g, '*').replace(/÷/g, '/');
  if (!/[+\-*/]/.test(expression)) return null;
  const result = evaluateExpression(expression);
  if (result == null) {
    return {
      kind: 'math',
      category: '计算',
      answer: '这个算式我没法安全计算，换一种写法试试？'
    };
  }
  return {
    kind: 'math',
    category: '计算',
    answer: `${expression.replace(/\s+/g, '')} = ${formatNumber(result)}。`
  };
}

function lookupKnowledge(text) {
  const normalized = normalizeText(text);
  if (!normalized) return null;
  let best = null;
  for (const entry of KNOWLEDGE) {
    let score = 0;
    for (const keyword of entry.keywords) {
      const normalizedKeyword = normalizeText(keyword);
      if (normalizedKeyword && normalized.includes(normalizedKeyword)) {
        score += normalizedKeyword.length * 2 + 2;
      }
    }
    if (score > 0 && (!best || score > best.score)) {
      best = { entry, score };
    }
  }
  if (!best || best.score < 5) return null;
  return {
    kind: 'knowledge',
    id: best.entry.id,
    category: best.entry.category,
    answer: best.entry.answer,
    confidence: best.score
  };
}

/**
 * 解析日常问题。返回 { kind, category, answer } 或 null。
 * 顺序很重要：时间、天气、单位、算术优先于关键词知识。
 */
export function resolveDailyQuestion(text, options = {}) {
  const source = String(text ?? '').trim();
  if (!source) return null;
  const now = options.now instanceof Date ? options.now : new Date();

  return (
    dateTimeAnswer(source, now) ??
    weatherAnswer(source) ??
    unitAnswer(source) ??
    mathAnswer(source, now) ??
    lookupKnowledge(source)
  );
}
